/**
 * Smidr Hugo Theme - Command Palette & Fuzzy Search
 * Shortcut: Cmd+K (Mac) or Ctrl+K (Windows/Linux)
 */

(function () {
  'use strict';

  let searchIndex = null;
  let isIndexLoading = false;
  let activeIndex = -1;

  const backdrop = document.getElementById('command-palette');
  const input = document.getElementById('palette-search-input');
  const resultsContainer = document.getElementById('palette-results');
  const triggerBtn = document.getElementById('search-trigger-btn');

  if (!backdrop || !input || !resultsContainer) return;

  // Open / Close functions
  function openPalette() {
    backdrop.classList.add('active');
    backdrop.setAttribute('aria-hidden', 'false');
    input.value = '';
    input.focus();
    renderDefaultActions();
    loadSearchIndex();
  }

  function closePalette() {
    backdrop.classList.remove('active');
    backdrop.setAttribute('aria-hidden', 'true');
    activeIndex = -1;
  }

  // Toggle on Cmd+K or Ctrl+K
  document.addEventListener('keydown', (e) => {
    if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') {
      e.preventDefault();
      if (backdrop.classList.contains('active')) {
        closePalette();
      } else {
        openPalette();
      }
    } else if (e.key === 'Escape' && backdrop.classList.contains('active')) {
      closePalette();
    }
  });

  // Trigger button click
  if (triggerBtn) {
    triggerBtn.addEventListener('click', openPalette);
  }

  // Click outside modal to close
  backdrop.addEventListener('click', (e) => {
    if (e.target === backdrop) {
      closePalette();
    }
  });

  // Load search index JSON generated by Hugo
  async function loadSearchIndex() {
    if (searchIndex || isIndexLoading) return;
    isIndexLoading = true;
    try {
      const langPrefix = document.documentElement.lang === 'de' ? '/de' : '';
      const res = await fetch(`${langPrefix}/index.json`);
      if (res.ok) {
        searchIndex = await res.json();
      }
    } catch (err) {
      console.warn('Could not load search index:', err);
    } finally {
      isIndexLoading = false;
    }
  }

  // Default quick actions when query is empty
  function renderDefaultActions() {
    const isDark = document.documentElement.getAttribute('data-theme') !== 'light';
    const isDe = document.documentElement.lang === 'de';

    const defaultItems = [
      {
        icon: isDark ? '☀️' : '🌙',
        title: isDe ? 'Farbschema umschalten (Hell/Dunkel)' : 'Toggle Theme (Light/Dark)',
        badge: 'Action',
        action: () => {
          window.toggleTheme();
          closePalette();
        }
      },
      {
        icon: '🔗',
        title: isDe ? 'Aktuellen Link in Zwischenablage kopieren' : 'Copy Current Page Link',
        badge: 'Action',
        action: async () => {
          await navigator.clipboard.writeText(window.location.href);
          alert(isDe ? 'Link kopiert!' : 'Link copied to clipboard!');
          closePalette();
        }
      },
      {
        icon: '🌐',
        title: isDe ? 'Switch to English' : 'Auf Deutsch wechseln',
        badge: 'Locale',
        action: () => {
          const target = isDe ? '/' : '/de/';
          window.location.href = target;
        }
      }
    ];

    renderItems(defaultItems, isDe ? 'Schnellaktionen' : 'Quick Actions');
  }

  // Fuzzy match score calculation
  function scoreMatch(query, text) {
    if (!text) return -1;
    const q = query.toLowerCase();
    const t = text.toLowerCase();
    if (t.includes(q)) return 100 - t.indexOf(q);
    
    // Fuzzy matching character by character
    let score = 0;
    let tIdx = 0;
    for (let i = 0; i < q.length; i++) {
      const char = q[i];
      const foundIdx = t.indexOf(char, tIdx);
      if (foundIdx === -1) return -1;
      score += 10 - (foundIdx - tIdx);
      tIdx = foundIdx + 1;
    }
    return score;
  }

  // Search input handler
  input.addEventListener('input', () => {
    const query = input.value.trim();
    if (!query) {
      renderDefaultActions();
      return;
    }

    if (!searchIndex) {
      resultsContainer.innerHTML = `<li class="palette-item"><span class="palette-item-title">Loading search index...</span></li>`;
      return;
    }

    const matches = [];
    for (const item of searchIndex) {
      const titleScore = scoreMatch(query, item.title);
      const descScore = scoreMatch(query, item.description || item.summary || '');
      const tagScore = item.tags ? scoreMatch(query, item.tags.join(' ')) : -1;
      
      const maxScore = Math.max(titleScore * 2, descScore, tagScore * 1.5);
      if (maxScore > 0) {
        matches.push({
          icon: '📄',
          title: item.title,
          badge: item.section || 'Post',
          url: item.permalink,
          score: maxScore
        });
      }
    }

    matches.sort((a, b) => b.score - a.score);

    const isDe = document.documentElement.lang === 'de';
    if (matches.length === 0) {
      resultsContainer.innerHTML = `
        <li class="palette-item">
          <span class="palette-item-title">${isDe ? 'Keine Treffer für' : 'No results found for'} "${query}"</span>
        </li>
      `;
      return;
    }

    renderItems(matches.slice(0, 8), isDe ? 'Suchergebnisse' : 'Search Results');
  });

  // Render items into container
  function renderItems(items, sectionTitle) {
    resultsContainer.innerHTML = '';
    
    if (sectionTitle) {
      const titleEl = document.createElement('li');
      titleEl.className = 'palette-section-title';
      titleEl.textContent = sectionTitle;
      resultsContainer.appendChild(titleEl);
    }

    items.forEach((item, index) => {
      const li = document.createElement('li');
      li.className = 'palette-item' + (index === 0 ? ' selected' : '');
      li.setAttribute('role', 'option');
      li.dataset.index = index;

      li.innerHTML = `
        <div class="palette-item-left">
          <span class="palette-item-icon">${item.icon}</span>
          <span class="palette-item-title">${item.title}</span>
        </div>
        <span class="palette-item-badge">${item.badge}</span>
      `;

      li.addEventListener('click', () => {
        if (item.action) {
          item.action();
        } else if (item.url) {
          window.location.href = item.url;
        }
      });

      resultsContainer.appendChild(li);
    });

    activeIndex = 0;
  }

  // Keyboard navigation inside results
  input.addEventListener('keydown', (e) => {
    const items = resultsContainer.querySelectorAll('.palette-item');
    if (items.length === 0) return;

    if (e.key === 'ArrowDown') {
      e.preventDefault();
      activeIndex = (activeIndex + 1) % items.length;
      updateSelection(items);
    } else if (e.key === 'ArrowUp') {
      e.preventDefault();
      activeIndex = (activeIndex - 1 + items.length) % items.length;
      updateSelection(items);
    } else if (e.key === 'Enter') {
      e.preventDefault();
      if (items[activeIndex]) {
        items[activeIndex].click();
      }
    }
  });

  function updateSelection(items) {
    items.forEach((item, idx) => {
      if (idx === activeIndex) {
        item.classList.add('selected');
        item.scrollIntoView({ block: 'nearest' });
      } else {
        item.classList.remove('selected');
      }
    });
  }

})();
